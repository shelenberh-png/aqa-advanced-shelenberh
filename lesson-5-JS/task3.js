// task 3 through 'for' loop
const number = 5;
for (let i = 1; i <= 10; i++) {
  const result = number * i;
  console.log(`${number} x ${i} = ${result}`);
}
// task 3 through 'while' loop
let i = 1;
while (i <= 10) {
  const result = number * i;
  console.log(`${number} x ${i} = ${result}`);
  i++;
}